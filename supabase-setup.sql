create extension if not exists btree_gist;

create table if not exists public.services (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  category text not null,
  name text not null,
  price numeric(10,2) not null check (price >= 0),
  duration_minutes integer not null check (duration_minutes between 15 and 480),
  deposit_percent numeric(5,2) not null default 40 check (deposit_percent between 0 and 100),
  active boolean not null default true,
  display_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.business_hours (
  id bigint generated by default as identity primary key,
  day_of_week smallint not null unique check (day_of_week between 0 and 6),
  open_time time not null default '08:00',
  close_time time not null default '19:00',
  slot_interval_minutes integer not null default 30 check (slot_interval_minutes between 15 and 240),
  active boolean not null default true,
  updated_at timestamptz not null default now(),
  check (close_time > open_time)
);

create table if not exists public.blocked_times (
  id uuid primary key default gen_random_uuid(),
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  reason text,
  created_at timestamptz not null default now(),
  check (ends_at > starts_at)
);

create table if not exists public.appointments (
  id uuid primary key default gen_random_uuid(),
  service_id uuid not null references public.services(id),
  customer_name text not null check (char_length(customer_name) between 3 and 120),
  customer_phone text not null,
  customer_phone_digits text not null check (char_length(customer_phone_digits) between 10 and 13),
  notes text check (notes is null or char_length(notes) <= 800),
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  status text not null default 'pending' check (status in ('pending','confirmed','completed','cancelled','no_show')),
  service_name_snapshot text not null,
  price_snapshot numeric(10,2) not null,
  deposit_percent_snapshot numeric(5,2) not null,
  deposit_amount_snapshot numeric(10,2) not null,
  source text not null default 'website',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_at > starts_at)
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

-- Impede sobreposição de horários confirmados ou aguardando confirmação,
-- inclusive quando duas clientes tentam reservar simultaneamente.
do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'appointments_no_overlap'
  ) then
    alter table public.appointments
      add constraint appointments_no_overlap
      exclude using gist (
        tstzrange(starts_at, ends_at, '[)') with &&
      ) where (status in ('pending','confirmed'));
  end if;
end $$;

