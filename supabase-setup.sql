create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = (select auth.uid())
  );
$$;

create or replace function public.get_available_slots(
  p_service_id uuid,
  p_date date
)
returns table(slot_time time, label text)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_duration integer;
  v_open time;
  v_close time;
  v_interval integer;
  v_day smallint;
  v_timezone constant text := 'America/Sao_Paulo';
begin
  if p_date < current_date or p_date > current_date + 120 then
    return;
  end if;

  select duration_minutes into v_duration
  from public.services
  where id = p_service_id and active = true;

  if v_duration is null then
    return;
  end if;

  v_day := extract(dow from p_date)::smallint;

  select open_time, close_time, slot_interval_minutes
    into v_open, v_close, v_interval
  from public.business_hours
  where day_of_week = v_day and active = true;

  if v_open is null then
    return;
  end if;

  return query
  with candidates as (
    select gs as local_start,
           gs + make_interval(mins => v_duration) as local_end
    from generate_series(
      p_date + v_open,
      p_date + v_close - make_interval(mins => v_duration),
      make_interval(mins => v_interval)
    ) as gs
  )
  select c.local_start::time as slot_time,
         to_char(c.local_start, 'HH24:MI') as label
  from candidates c
  where (c.local_start at time zone v_timezone) > now()
    and not exists (
      select 1
      from public.appointments a
      where a.status in ('pending','confirmed')
        and tstzrange(a.starts_at, a.ends_at, '[)') &&
            tstzrange(
              c.local_start at time zone v_timezone,
              c.local_end at time zone v_timezone,
              '[)'
            )
    )
    and not exists (
      select 1
      from public.blocked_times b
      where tstzrange(b.starts_at, b.ends_at, '[)') &&
            tstzrange(
              c.local_start at time zone v_timezone,
              c.local_end at time zone v_timezone,
              '[)'
            )
    )
  order by c.local_start;
end;
$$;

create or replace function public.create_public_appointment(
  p_service_id uuid,
  p_date date,
  p_start_time time,
  p_customer_name text,
  p_customer_phone text,
  p_notes text default null
)
returns table(
  appointment_id uuid,
  service_name text,
  price numeric,
  deposit_amount numeric,
  starts_at timestamptz,
  ends_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_service public.services%rowtype;
  v_phone_digits text;
  v_start timestamptz;
  v_end timestamptz;
  v_id uuid;
  v_timezone constant text := 'America/Sao_Paulo';
begin
  select * into v_service
  from public.services
  where id = p_service_id and active = true;

  if not found then
    raise exception 'SERVICO_INDISPONIVEL';
  end if;

  if trim(coalesce(p_customer_name, '')) = '' or char_length(trim(p_customer_name)) < 3 then
    raise exception 'NOME_INVALIDO';
  end if;

  v_phone_digits := regexp_replace(coalesce(p_customer_phone, ''), '\D', '', 'g');
  if char_length(v_phone_digits) < 10 or char_length(v_phone_digits) > 13 then
    raise exception 'TELEFONE_INVALIDO';
  end if;

  if not exists (
    select 1 from public.get_available_slots(p_service_id, p_date)
    where slot_time = p_start_time
  ) then
    raise exception 'HORARIO_INDISPONIVEL';
  end if;

  -- Reduz envios duplicados acidentais do mesmo telefone.
  if exists (
    select 1 from public.appointments
    where customer_phone_digits = v_phone_digits
      and created_at > now() - interval '90 seconds'
  ) then
    raise exception 'AGUARDE_ANTES_DE_ENVIAR_NOVAMENTE';
  end if;

  v_start := (p_date + p_start_time) at time zone v_timezone;
  v_end := v_start + make_interval(mins => v_service.duration_minutes);

  begin
    insert into public.appointments (
      service_id,
      customer_name,
      customer_phone,
      customer_phone_digits,
      notes,
      starts_at,
      ends_at,
      status,
      service_name_snapshot,
      price_snapshot,
      deposit_percent_snapshot,
      deposit_amount_snapshot,
      source
    ) values (
      v_service.id,
      trim(p_customer_name),
      trim(p_customer_phone),
      v_phone_digits,
      nullif(trim(coalesce(p_notes, '')), ''),
      v_start,
      v_end,
      'pending',
      v_service.name,
      v_service.price,
      v_service.deposit_percent,
      round(v_service.price * v_service.deposit_percent / 100, 2),
      'website'
    ) returning id into v_id;
  exception
    when exclusion_violation then
      raise exception 'HORARIO_INDISPONIVEL';
  end;

  return query
  select
    v_id,
    v_service.name,
    v_service.price,
    round(v_service.price * v_service.deposit_percent / 100, 2),
    v_start,
    v_end;
end;
$$;

create or replace function public.admin_create_block(
  p_date date,
  p_start_time time,
  p_end_time time,
  p_reason text default null
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id uuid;
  v_timezone constant text := 'America/Sao_Paulo';
begin
  if not public.is_admin() then
    raise exception 'ACESSO_NEGADO';
  end if;
  if p_end_time <= p_start_time then
    raise exception 'INTERVALO_INVALIDO';
  end if;

  insert into public.blocked_times(starts_at, ends_at, reason)
  values (
    (p_date + p_start_time) at time zone v_timezone,
    (p_date + p_end_time) at time zone v_timezone,
    nullif(trim(coalesce(p_reason, '')), '')
  ) returning id into v_id;

  return v_id;
end;
$$;

