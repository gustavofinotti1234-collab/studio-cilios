-- Remove políticas anteriores deste projeto, caso o arquivo seja executado novamente.
do $$
declare p record;
begin
  for p in
    select schemaname, tablename, policyname
    from pg_policies
    where schemaname = 'public'
      and tablename in ('services','business_hours','blocked_times','appointments','admin_users')
  loop
    execute format('drop policy if exists %I on %I.%I', p.policyname, p.schemaname, p.tablename);
  end loop;
end $$;

